import fsPromises from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import url from 'node:url';

const root = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const schemaPath = path.join(root, 'schemas/workbench-colors.json');
const outPath = path.join(root, 'src/types/workbench-colors.d.ts');

const schema = JSON.parse(await fsPromises.readFile(schemaPath, 'utf8')) as {
  properties?: Record<string, unknown>;
};

const keys = Object.keys(schema.properties ?? {}).sort((a, b) => a.localeCompare(b));

if (keys.length === 0) {
  throw new Error(`No properties in ${schemaPath}`);
}

const union = keys.map(key => `  | ${JSON.stringify(key)}`).join('\n');

const source = `/* Generated by scripts/gen-workbench-keys.ts — do not edit by hand. */
/* Source: schemas/workbench-colors.json (${keys.length} keys) */

export type WorkbenchColorKey =
${union};

export type HexColor = \`#\${string}\`;

export type WorkbenchColors = Partial<Record<WorkbenchColorKey, HexColor>>;
`;

await fsPromises.writeFile(outPath, source);
process.stdout.write(`Wrote ${keys.length} keys → ${outPath}\n`);
